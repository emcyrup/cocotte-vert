-- シフト変更申請に「保留」を足す。
--
-- これまでは申請＝pending（店長の承認待ち）だけだった。公式LINE のやりとりの中で
-- 本人が内容を確認して「確定」できるようにしたため、状態の意味が変わる:
--
--   pending  … Bot が内容を確認して、本人の返事を待っている
--   approved … 本人が「確定」と答えた。週次シフト表へ反映済み
--   held     … 本人が「保留」と答えた。店長が管理画面で判断する（今回追加）
--   rejected … 取りやめ・却下
--
-- ADD VALUE は同じトランザクション内でその値を使えないが、ここでは追加するだけなので問題ない。
ALTER TYPE shift_request_status ADD VALUE IF NOT EXISTS 'held';
